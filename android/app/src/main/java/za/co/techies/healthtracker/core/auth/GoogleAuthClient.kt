package za.co.techies.healthtracker.core.auth

import android.content.Context
import android.util.Log
import androidx.credentials.CredentialManager
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider
import kotlinx.coroutines.tasks.await
import za.co.techies.healthtracker.R
import za.co.techies.healthtracker.core.text.UiText
import za.co.techies.healthtracker.core.text.asUiText
import za.co.techies.healthtracker.core.text.uiText

/** The outcome of a sign-in attempt, so the caller never has to catch credential exceptions. */
sealed interface SignInResult {
    data class Success(val uid: String) : SignInResult

    /** The user backed out of the account chooser. Not an error; show nothing. */
    data object Cancelled : SignInResult

    data class Failure(val message: UiText, val cause: Throwable? = null) : SignInResult

    /** google-services.json is missing, so there is nothing to sign in against. */
    data object NotConfigured : SignInResult
}

/**
 * Google single sign-on (Requirement 1), via Credential Manager.
 *
 * Credential Manager is used rather than the older GoogleSignIn API, which is deprecated. The flow
 * is: Credential Manager returns a Google ID token, that token is exchanged for a Firebase
 * session, and the API then validates the Firebase token on every request.
 *
 * The web client id is looked up by resource name at run time rather than referenced as
 * `R.string.default_web_client_id`. That resource is generated by the Google Services plugin,
 * which is only applied when google-services.json is present — a direct reference would stop the
 * project compiling for anyone who has not set Firebase up yet.
 */
class GoogleAuthClient(
    private val context: Context,
    private val firebaseAuth: FirebaseAuth?
) {

    private val credentialManager by lazy { CredentialManager.create(context) }

    /** The OAuth web client id generated into resources by the Google Services plugin. */
    private val webClientId: String?
        get() = runCatching {
            val id = context.resources.getIdentifier(
                "default_web_client_id", "string", context.packageName
            )
            if (id == 0) null else context.getString(id)
        }.getOrNull()

    val isConfigured: Boolean get() = firebaseAuth != null && !webClientId.isNullOrBlank()

    suspend fun signIn(): SignInResult {
        val clientId = webClientId

        if (firebaseAuth == null || clientId.isNullOrBlank()) {
            Log.w(TAG, "Sign-in unavailable: google-services.json has not been added")
            return SignInResult.NotConfigured
        }

        return try {
            // GetSignInWithGoogleOption shows the full account chooser, including accounts not
            // previously used with this app. GetGoogleIdOption with filterByAuthorizedAccounts
            // would silently show nothing on a fresh install, which reads as a broken button.
            val option = GetSignInWithGoogleOption.Builder(clientId).build()
            val request = GetCredentialRequest.Builder().addCredentialOption(option).build()

            val response = credentialManager.getCredential(context, request)
            val credential = GoogleIdTokenCredential.createFrom(response.credential.data)

            val firebaseCredential = GoogleAuthProvider.getCredential(credential.idToken, null)
            val authResult = firebaseAuth.signInWithCredential(firebaseCredential).await()

            val uid = authResult.user?.uid
                ?: return SignInResult.Failure(uiText(R.string.auth_err_no_user))

            Log.i(TAG, "Signed in as $uid")
            SignInResult.Success(uid)
        } catch (cancelled: GetCredentialCancellationException) {
            Log.d(TAG, "Sign-in cancelled by the user")
            SignInResult.Cancelled
        } catch (none: NoCredentialException) {
            Log.w(TAG, "No Google account available on this device", none)
            SignInResult.Failure(uiText(R.string.auth_err_no_google_account))
        } catch (credentialError: GetCredentialException) {
            // The usual cause is a SHA-1 fingerprint that is not registered in Firebase, which
            // surfaces here as an opaque failure. Naming it saves a long debugging session.
            Log.e(TAG, "Credential Manager refused the request", credentialError)
            SignInResult.Failure(uiText(R.string.auth_err_google_refused), credentialError)
        } catch (e: Exception) {
            Log.e(TAG, "Sign-in failed", e)
            SignInResult.Failure(e.message?.asUiText() ?: uiText(R.string.auth_err_sign_in_failed), e)
        }
    }

    fun signOut() {
        firebaseAuth?.signOut()
        Log.i(TAG, "Signed out")
    }

    fun currentUid(): String? = firebaseAuth?.currentUser?.uid

    private companion object {
        const val TAG = "GoogleAuthClient"
    }
}
